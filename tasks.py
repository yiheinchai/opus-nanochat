class SmolTalk(HubTask):
    """ 460K general conversations (train), 24K (test), synthetically generated by a bigger LLM """

    def __init__(self, split, stop=None):
        super().__init__(load_hub_dataset("HuggingFaceTB/smol-smoltalk", split=split), stop)

    def get_example(self, index):
        return {"messages": self.row(index)["messages"]}

# -----------------------------------------------------------------------------
# Multiple choice

def render_mc(question, letters, choices):
    # Two subtle details that matter for small models:
    # 1) the letter comes *after* the choice, which makes it easier to "bind" them
    # 2) no space before the letter: "=A" so that "A" is the exact same token as in the answer
    query = f"Multiple Choice question: {question}\n"
    query += "".join(f"- {choice}={letter}\n" for letter, choice in zip(letters, choices))
    query += "\nRespond only with the letter of the correct answer."
    return query

class MMLU(HubTask):
    """ 57 subjects of multiple choice questions. auxiliary_train is 100K rows, test is 14K """
    letters = ('A', 'B', 'C', 'D')

    def __init__(self, split, stop=None):
        super().__init__(load_hub_dataset("cais/mmlu", "all", split=split), stop)

    def get_example(self, index):
        row = self.row(index)
        messages = [
            {"role": "user", "content": render_mc(row["question"], self.letters, row["choices"])},
            {"role": "assistant", "content": self.letters[row["answer"]]},
        ]
        return {"messages": messages, "letters": self.letters}

    def evaluate(self, conversation, completion):
        return completion == conversation["messages"][-1]["content"]

class ARC(MMLU):
    """ Grade school science questions, ARC-Easy or ARC-Challenge """

    def __init__(self, subset, split, stop=None):
        HubTask.__init__(self, load_hub_dataset("allenai/ai2_arc", subset, split=split), stop)

    def get_example(self, index):
        row = self.row(index)
        letters = tuple(row["choices"]["label"]) # usually A,B,C,D but not always
        messages = [
            {"role": "user", "content": render_mc(row["question"], letters, row["choices"]["text"])},
            {"role": "assistant", "content": row["answerKey"]},
        ]
        return {"messages": messages, "letters": letters}

# -----------------------------------------------------------------------------
# Math, with a calculator tool

ANSWER_RE = re.compile(r"#### (\-?[0-9\.\,]+)")
def extract_answer(completion):
    match = ANSWER_RE.search(completion)
    return match.group(1).strip().replace(",", "") if match else None

class GSM8K(HubTask):
    """ 8K grade school math word problems. Solutions use a calculator, written as <<12/60=0.2>> """

    def __init__(self, split, stop=None):
        super().__init__(load_hub_dataset("openai/gsm8k", "main", split=split), stop)

    def get_example(self, index):
        row = self.row(index)
        # turn every <<expr=result>> into a python tool call, followed by its output
        parts = []
        for chunk in re.split(r'(<<[^>]+>>)', row["answer"]):
            if chunk.startswith('<<') and chunk.endswith('>>'):
                expr, _, result = chunk[2:-2].rpartition('=')
                parts.append({"type": "python", "text": expr})
                parts.append({"type": "python_output", "text": result})
            else:
                parts.append({"type": "text", "text": chunk})
        messages = [
            {"role": "user", "content": row["question"]},
            {"role": "assistant", "content": parts},
        ]
        return {"messages": messages}

    def evaluate(self, conversation, completion):
        reference = conversation["messages"][-1]["content"][-1]["text"] # the last part has "#### 72"
        return extract_answer(completion) == extract_answer(reference)

