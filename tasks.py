# How many r are in strawberry? (from nanochat's SpellingBee task)

class SpellingBee(Task):
    """ Synthetic: count a letter in a word. Spell it out by hand, then double check with python """

    def __init__(self, size, split):
        super().__init__()
        self.size, self.split = size, split
        path = download_file("https://raw.githubusercontent.com/dwyl/english-words/refs/heads/master/words_alpha.txt", "words_alpha.txt")
        with open(path, encoding="utf-8") as f:
            self.words = [line.strip() for line in f]

    def num_examples(self):
        return self.size

    def get_example(self, index):
        # every example is generated on the fly from its own seed, test seeds never overlap train seeds
        rng = random.Random(index if self.split == "train" else 10_000_000 + index)
        word = rng.choice(self.words)
        letter = rng.choice(word) if rng.random() < 0.9 else rng.choice("abcdefghijklmnopqrstuvwxyz")
        count = word.count(letter)
        template = rng.choice([
            "How many {l} are in the word {w}", "How many {l} are in {w}", "Count the number of {l} in {w}",
            "How many times does {l} appear in {w}", "In the word {w}, how many {l} are there",
            "How many {l}s are in {w}", "What is the count of {l} in {w}",
        ])
        user = template.format(l=f"'{letter}'" if rng.random() < 0.5 else letter, w=word)
        user = user + "?" if rng.random() < 0.5 else user
        # the ideal response: spell the word out, count by hand, double check with python
        manual = f"We are asked to find the number '{letter}' in the word '{word}'. Let me try a manual approach first.\n\n"
        manual += f"First spell the word out:\n{word}:{','.join(word)}\n\nThen count the occurrences of '{letter}':\n"
        running = 0
        for i, char in enumerate(word, 1):
            if char == letter:
                running += 1
                manual += f"{i}:{char} hit! count={running}\n"
            else:
                manual += f"{i}:{char}\n"
        manual += f"\nThis gives us {running}.\n\nLet me double check this using Python:\n\n"
        parts = [
            {"type": "text", "text": manual},
            {"type": "python", "text": f"'{word}'.count('{letter}')"},
            {"type": "python_output", "text": str(count)},
            {"type": "text", "text": f"\n\nPython gives us {count}.\n\nMy final answer is:\n\n#### {count}"},
        ]
        return {"messages": [{"role": "user", "content": user}, {"role": "assistant", "content": parts}]}

    def evaluate(self, conversation, completion):
        reference = conversation["messages"][-1]["content"][-1]["text"]
        return extract_answer(completion) == extract_answer(reference)
