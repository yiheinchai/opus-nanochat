"""
Tasks: datasets of conversations, and (optionally) a way to grade the assistant's answer.
Mirrors the tasks/ directory of nanochat.
"""

import re
import json
import random
import urllib.request
import numpy as np
import pyarrow as pa
import pyarrow.parquet as pq

from common import download_file

# -----------------------------------------------------------------------------
# A tiny stand-in for HuggingFace datasets: every dataset on the hub has a parquet export

def load_hub_dataset(repo_id, subset="default", split="train"):
    listing = f"https://huggingface.co/api/datasets/{repo_id}/parquet/{subset}/{split}"
    with urllib.request.urlopen(listing) as response:
        urls = json.loads(response.read())
    slug = repo_id.replace("/", "--")
    paths = [download_file(url, f"data/{slug}/{subset}/{split}/{i:05d}.parquet") for i, url in enumerate(urls)]
    return pa.concat_tables([pq.read_table(p) for p in paths])

class Task:
    """ A list of conversations. Subclasses implement get_example (and evaluate, if gradable). """

    def __init__(self, stop=None):
        self.stop = stop # optionally only use the first `stop` examples

    def __len__(self):
        n = self.num_examples()
        return n if self.stop is None else min(n, self.stop)

    def __getitem__(self, index):
        return self.get_example(index)

    def reward(self, conversation, completion):
        # in RL, the reward is simply whether the answer was correct
        return float(self.evaluate(conversation, completion))

class HubTask(Task):
    """ A task backed by a parquet table, shuffled once with a fixed seed """

    def __init__(self, table, stop=None):
        super().__init__(stop)
        self.table = table
        self.perm = np.random.default_rng(42).permutation(table.num_rows)

    def num_examples(self):
        return self.table.num_rows

    def row(self, index):
        i = int(self.perm[index])
        return {col: self.table[col][i].as_py() for col in self.table.column_names}

class TaskMixture(Task):
    """ Several tasks, shuffled together. Pass a task in twice to oversample it. """

    def __init__(self, tasks):
        super().__init__()
        self.tasks = tasks
        self.index_map = [(t, i) for t, task in enumerate(tasks) for i in range(len(task))]
        random.Random(42).shuffle(self.index_map)

    def num_examples(self):
        return len(self.index_map)

    def get_example(self, index):
        t, i = self.index_map[index]
        return self.tasks[t][i]

